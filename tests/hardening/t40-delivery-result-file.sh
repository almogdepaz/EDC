#!/usr/bin/env bash
# t40-delivery-result-file: delivery review writes structured last-run.json.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
SCRIPT="$ROOT/plugins/edc/scripts/edc-delivery-review.sh"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

mkdir -p "$TMP/bin"
cat > "$TMP/bin/claude" <<'MOCK'
#!/usr/bin/env bash
set -euo pipefail
prompt=$(cat)
if [ "${EDC_T40_MISSING_REPORT:-0}" = "1" ]; then
  exit 0
fi
report=$(printf '%s\n' "$prompt" | awk '/^DELIVERY_REPORT_PATH: /{print $2; exit}')
printf '# Delivery\n\n## Verdict\n\nok\n' > "$report"
MOCK
chmod +x "$TMP/bin/claude"

setup_repo() {
  rm -rf "$TMP/repo"
  mkdir -p "$TMP/repo"
  cd "$TMP/repo"
  export GIT_CONFIG_GLOBAL=/dev/null
  export GIT_CONFIG_SYSTEM=/dev/null
  git init -q
  git config user.email test@test.com
  git config user.name Test
  git config commit.gpgsign false
  printf 'one\n' > file.txt
  git add file.txt
  git commit -q -m init
  printf 'two\n' > file.txt
  git add file.txt
  git commit -q -m change
  mkdir -p edc-context/modules edc-context/reports edc-context/build .edc/skills/edc-delivery-review/references
  head=$(git rev-parse HEAD)
  cat > edc-context/manifest.json <<EOF
{"schemaVersion":2,"sourceCommit":"$head","modules":[{"name":"root","doc":"edc-context/modules/root.md","priority":10,"match":{"prefixes":[""]}}],"unmapped":{"allowedGlobs":["*"]},"policy":{"defaultMode":"advisory","unmatchedPathPolicy":"warn-allow"},"repoContextFile":"edc-context/index.md","reports":{"issues":"edc-context/reports/issues.md","complexity":"edc-context/reports/complexity.md"},"build":{"buildInfoFile":"edc-context/build/build.json"},"coverage":{"mappedFileCount":1,"unmappedFileCount":0,"ambiguousPathCount":0}}
EOF
  printf '# Index\n\n## Route by path/task\n' > edc-context/index.md
  printf '# Root\n\n## Scope\n' > edc-context/modules/root.md
  printf '## Issues\n' > edc-context/reports/issues.md
  printf '## Complexity\n' > edc-context/reports/complexity.md
  printf '{}\n' > edc-context/build/build.json
  printf '# Agent Instructions\n\nThis repo ships deep architectural context generated by EDC.\n\nSee [`edc-context/index.md`](edc-context/index.md).\nSee [`edc-context/manifest.json`](edc-context/manifest.json).\n' > AGENTS.md
  printf 'DELIVERY_SKILL\n' > .edc/skills/edc-delivery-review/SKILL.md
  printf 'SPEC\n' > .edc/skills/edc-delivery-review/references/spec-axis.md
  printf 'ARCH\n' > .edc/skills/edc-delivery-review/references/architecture-axis.md
  printf 'REPORT\n' > .edc/skills/edc-delivery-review/references/reporting.md
}

setup_repo
PATH="$TMP/bin:$PATH" EDC_AGENT_CLI=claude bash "$SCRIPT" HEAD --base HEAD~1 >"$TMP/good.out" 2>"$TMP/good.err"
node --input-type=module <<'NODE'
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const result = JSON.parse(readFileSync('edc-context/build/last-run.json', 'utf8'));
assert.equal(result.kind, 'delivery-review');
assert.equal(result.exitCode, 0);
assert.equal(result.reasonCode, 'success');
assert.equal(result.finalReview, 'delivery-review-HEAD.md');
NODE
echo "PASS: delivery-review writes structured success result"

setup_repo
set +e
PATH="$TMP/bin:$PATH" EDC_AGENT_CLI=claude EDC_T40_MISSING_REPORT=1 bash "$SCRIPT" HEAD --base HEAD~1 >"$TMP/bad.out" 2>"$TMP/bad.err"
rc=$?
set -e
if [ "$rc" -ne 0 ]; then
  node --input-type=module <<'NODE'
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const result = JSON.parse(readFileSync('edc-context/build/last-run.json', 'utf8'));
assert.equal(result.kind, 'delivery-review');
assert.equal(result.exitCode, 1);
assert.equal(result.reasonCode, 'delivery-report-validation');
NODE
  echo "PASS: delivery-review writes structured failure result"
else
  echo "FAIL: delivery-review missing report should fail"
  cat "$TMP/bad.out" "$TMP/bad.err"
  exit 1
fi
