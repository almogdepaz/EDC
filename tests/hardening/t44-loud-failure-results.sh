#!/usr/bin/env bash
# t44-loud-failure-results: common orchestrator failures write specific structured reasons.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
TMP=$(mktemp -d)
MOCK_BIN="$TMP/bin"
trap 'rm -rf "$TMP"' EXIT

printf '=== T44: loud structured failure results ===\n'

mkdir -p "$MOCK_BIN"
cat > "$MOCK_BIN/claude" <<'SH'
#!/usr/bin/env bash
set -euo pipefail
cat >/dev/null
printf 'mock agent failure\n' >&2
exit 1
SH
chmod +x "$MOCK_BIN/claude"

setup_repo() {
  local repo="$1"
  rm -rf "$repo"
  mkdir -p "$repo"
  cd "$repo"
  export GIT_CONFIG_GLOBAL=/dev/null
  export GIT_CONFIG_SYSTEM=/dev/null
  git init -q
  git config user.email t@example.com
  git config user.name T
  git config commit.gpgsign false
  mkdir -p src .edc/skills/edc-build-impl .edc/skills/edc-update-impl .edc/skills/edc-review/references .edc/skills/edc-audit/references
  echo one > src/app.ts
  git add src/app.ts
  git commit -q -m init
  printf '# Build\n' > .edc/skills/edc-build-impl/SKILL.md
  printf '# Update\n' > .edc/skills/edc-update-impl/SKILL.md
  printf '# Review\n' > .edc/skills/edc-review/SKILL.md
  printf '# Methodology\n' > .edc/skills/edc-review/references/methodology.md
  printf '# Adversarial\n' > .edc/skills/edc-review/references/adversarial.md
  printf '# Reporting\n' > .edc/skills/edc-review/references/reporting.md
  printf '# Patterns\n' > .edc/skills/edc-review/references/patterns.md
  printf '# Audit\nname: edc-audit\n' > .edc/skills/edc-audit/SKILL.md
  printf '# Scope\n' > .edc/skills/edc-audit/references/scope-and-standards.md
  printf '# Smell\n' > .edc/skills/edc-audit/references/smell-baseline.md
  printf '# Checks\n' > .edc/skills/edc-audit/references/quality-checks.md
  printf '# Reporting\n' > .edc/skills/edc-audit/references/reporting.md
}

write_stale_context() {
  mkdir -p edc-context/modules
  printf '# Repo\n\n## Module Map\n- app\n' > edc-context/index.md
  printf '# app\n\n## Files\n- src/app.ts\n' > edc-context/modules/app.md
  printf '{"schemaVersion":2,"sourceCommit":"deadbeef","policy":{"defaultMode":"advisory","unmatchedPathPolicy":"warn-allow"},"modules":[{"name":"app","priority":10,"doc":"edc-context/modules/app.md","match":{"prefixes":["src/"]}}]}\n' > edc-context/manifest.json
  cat > AGENTS.md <<'AGENTS'
# Agent Instructions

This repo ships deep architectural context generated by EDC. Read this file at session start before touching code.

See [edc-context/index.md](edc-context/index.md) and [edc-context/manifest.json](edc-context/manifest.json).
AGENTS
}

assert_result() {
  local kind="$1" reason="$2" hint_pattern="$3"
  node -e 'const [kind, reason, hintPattern] = process.argv.slice(1); const j=require("./edc-context/build/last-run.json"); process.exit(j.kind === kind && j.status === "failed" && Number(j.exitCode) === 1 && j.reasonCode === reason && new RegExp(hintPattern).test(j.hint || "") ? 0 : 1)' "$kind" "$reason" "$hint_pattern"
}

export PATH="$MOCK_BIN:$PATH"
export EDC_AGENT_CLI=claude

setup_repo "$TMP/build-repo"
cd "$TMP/build-repo"
result=0
out=$(bash "$ROOT/plugins/edc/scripts/edc-build.sh" --force 2>&1) || result=$?
if [ "$result" -ne 0 ] && assert_result build agent-failed 'edc build'; then
  echo "PASS: build agent failure writes specific structured result"
else
  echo "FAIL: build failure result was not specific. exit=$result"; echo "$out"; cat edc-context/build/last-run.json 2>/dev/null || true; exit 1
fi

setup_repo "$TMP/update-repo"
write_stale_context
result=0
out=$(bash "$ROOT/plugins/edc/scripts/edc-update.sh" --base HEAD 2>&1) || result=$?
if [ "$result" -ne 0 ] && assert_result update agent-failed 'edc update'; then
  echo "PASS: update agent failure writes specific structured result"
else
  echo "FAIL: update failure result was not specific. exit=$result"; echo "$out"; cat edc-context/build/last-run.json 2>/dev/null || true; exit 1
fi

setup_repo "$TMP/review-repo"
write_stale_context
echo two > src/app.ts
git add src/app.ts
git commit -q -m change
result=0
out=$(bash "$ROOT/plugins/edc/scripts/edc-review.sh" HEAD --base HEAD~1 2>&1) || result=$?
if [ "$result" -ne 0 ] && assert_result review context-recovery-failed 'edc update'; then
  echo "PASS: security review recovery failure writes specific structured result"
else
  echo "FAIL: review recovery result was not specific. exit=$result"; echo "$out"; cat edc-context/build/last-run.json 2>/dev/null || true; exit 1
fi

setup_repo "$TMP/audit-repo"
write_stale_context
result=0
out=$(bash "$ROOT/plugins/edc/scripts/edc-audit.sh" 2>&1) || result=$?
if [ "$result" -ne 0 ] && assert_result audit context-recovery-failed 'edc update'; then
  echo "PASS: quality review recovery failure writes specific structured result"
else
  echo "FAIL: audit recovery result was not specific. exit=$result"; echo "$out"; cat edc-context/build/last-run.json 2>/dev/null || true; exit 1
fi

printf '\nAll T44 checks passed.\n'
