#!/usr/bin/env bash
set -euo pipefail

printf '=== T42: phase result contract ===\n'

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

setup_repo() {
  local repo="$1"
  mkdir -p "$repo"
  (
    cd "$repo"
    git init -q
    git config user.email a@example.com
    git config user.name a
    touch tracked.txt
    git add tracked.txt
    git -c commit.gpgsign=false commit -q -m init
  )
}

run_recovery_after_failed_spawn() {
  local repo="$1"
  local mode="${2:-writes-complete-context}"
  local script="$TMP/recovery-$mode.sh"
  cat > "$script" <<'EOS'
#!/usr/bin/env bash
set -euo pipefail
cd "$TMP_REPO"

export EDC_AGENT_CLI="pi"
export EDC_BUILD_TIMEOUT=1
export EDC_UPDATE_TIMEOUT=1
export ROOT_UNDER_TEST

# shellcheck source=plugins/edc/scripts/edc-lib.sh
. "$ROOT_UNDER_TEST/plugins/edc/scripts/edc-lib.sh"
MANIFEST="$EDC_MANIFEST"
CLEAN_SLATE_SH="$TMP_REPO/clean-slate.sh"

cat > "$CLEAN_SLATE_SH" <<'CLEAN'
#!/usr/bin/env bash
exit 0
CLEAN
chmod +x "$CLEAN_SLATE_SH"

resolve_prompt() {
  printf 'prompt:%s\n' "$1"
}

edc_spawn() {
  if [ "$SPAWN_MODE" != "no-context" ]; then
    mkdir -p edc-context
    cat > "$EDC_INDEX" <<'EOF_INDEX'
# Index
## Module Map
- root
EOF_INDEX
    cat > "$MANIFEST" <<EOF_MANIFEST
{"schemaVersion":2,"sourceCommit":"$(git rev-parse HEAD)","repoContextFile":"edc-context/index.md","reports":{"issues":"edc-context/reports/issues.md","complexity":"edc-context/reports/complexity.md"},"build":{"buildInfoFile":"edc-context/build/build.json"},"policy":{"defaultMode":"advisory","unmatchedPathPolicy":"warn-allow"},"modules":[{"name":"root","doc":"edc-context/modules/root.md","priority":10,"match":{"exactFiles":["tracked.txt"]}}],"contextless":{"entries":[]},"unmapped":{"allowedGlobs":[]}}
EOF_MANIFEST
  fi
  if [ "$SPAWN_MODE" = "writes-complete-context" ] || [ "$SPAWN_MODE" = "times-out-with-complete-context" ]; then
    mkdir -p edc-context/modules edc-context/reports edc-context/build
    printf '# Root\n\n## Scope\n' > edc-context/modules/root.md
    printf '## Issues\n' > edc-context/reports/issues.md
    printf '## Complexity\n' > edc-context/reports/complexity.md
    printf '{"schemaVersion":2}\n' > edc-context/build/build.json
    cat > AGENTS.md <<'EOF_AGENTS'
# EDC agent orientation

This repo ships deep architectural context generated by EDC.
See `edc-context/index.md` and `edc-context/manifest.json`.
EOF_AGENTS
  fi
  if [ "$SPAWN_MODE" = "times-out-with-complete-context" ]; then
    return 124
  fi
  return 1
}

# shellcheck source=plugins/edc/scripts/edc-assert-fresh.sh
. "$ROOT_UNDER_TEST/plugins/edc/scripts/edc-assert-fresh.sh"
# shellcheck source=plugins/edc/scripts/edc-recover-context.sh
. "$ROOT_UNDER_TEST/plugins/edc/scripts/edc-recover-context.sh"
recover_context_if_needed
EOS
  chmod +x "$script"
  TMP_REPO="$repo" ROOT_UNDER_TEST="$ROOT" SPAWN_MODE="$mode" "$script" 2>&1
}

repo="$TMP/repo"
setup_repo "$repo"
if ! output=$(run_recovery_after_failed_spawn "$repo"); then
  echo "FAIL: recovery returned failure even though durable context validation passed"
  printf '%s\n' "$output"
  exit 1
fi

if grep -q 'EDC context recovery succeeded with warning' <<< "$output" \
  && grep -q 'edc-build subprocess reported failure' <<< "$output"; then
  echo "PASS: recovery accepts valid context after failed build rc and emits warning"
else
  echo "FAIL: recovery did not emit the expected success-with-warning diagnostics"
  printf '%s\n' "$output"
  exit 1
fi

timeout_repo="$TMP/timeout-repo"
setup_repo "$timeout_repo"
if timeout_output=$(run_recovery_after_failed_spawn "$timeout_repo" times-out-with-complete-context 2>&1); then
  echo "FAIL: recovery accepted complete context after timed-out subprocess"
  printf '%s\n' "$timeout_output"
  exit 1
fi

if grep -q 'edc-build subprocess timed out; refusing to continue' <<< "$timeout_output"; then
  echo "PASS: recovery never accepts outputs after timeout"
else
  echo "FAIL: timed-out recovery did not report hard failure"
  printf '%s\n' "$timeout_output"
  exit 1
fi

partial_repo="$TMP/partial-repo"
setup_repo "$partial_repo"
if partial_output=$(run_recovery_after_failed_spawn "$partial_repo" writes-partial-context 2>&1); then
  echo "FAIL: recovery accepted incomplete context after failed subprocess"
  printf '%s\n' "$partial_output"
  exit 1
fi

if grep -q 'EDC context recovery failed.' <<< "$partial_output" \
  && grep -q 'complete build output validation did not pass' <<< "$partial_output"; then
  echo "PASS: recovery rejects incomplete context after failed subprocess"
else
  echo "FAIL: incomplete recovery did not report complete-output validation failure"
  printf '%s\n' "$partial_output"
  exit 1
fi

failing_repo="$TMP/failing-repo"
setup_repo "$failing_repo"
if failure_output=$(run_recovery_after_failed_spawn "$failing_repo" no-context 2>&1); then
  echo "FAIL: recovery succeeded even though subprocess failed and context validation failed"
  printf '%s\n' "$failure_output"
  exit 1
fi

if grep -q 'EDC context recovery failed.' <<< "$failure_output" \
  && grep -q 'reason: edc-build subprocess failed and complete build output validation did not pass' <<< "$failure_output" \
  && grep -q 'next step: inspect the agent log' <<< "$failure_output"; then
  echo "PASS: recovery failure reports clear reason and next step"
else
  echo "FAIL: recovery failure did not report clear diagnostics"
  printf '%s\n' "$failure_output"
  exit 1
fi

printf '\nAll T42 checks passed.\n'
